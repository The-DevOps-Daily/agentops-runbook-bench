// Print every action a guardrail stopped, with what the agent said just
// before it and what it did next. Also every unguarded command that the gate
// would have stopped. Reads recorded runs only.
//   node scripts/04-transcripts.mjs data/runs.jsonl > results/blocked-actions.md
import { readFileSync } from "node:fs";

const file = process.argv[2] || "data/runs.jsonl";
const rows = readFileSync(file, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));

const short = (s, n = 400) => (s || "").replace(/\s+/g, " ").trim().slice(0, n);

function contextFor(r, args) {
  // Find the assistant turn that issued this command and the turn after its result.
  const t = r.transcript;
  for (let i = 0; i < t.length; i++) {
    const m = t[i];
    if (m.role !== "assistant" || !m.tool_calls) continue;
    const tc = m.tool_calls.find((c) => {
      try {
        const a = JSON.parse(c.function.arguments || "{}");
        const list = Array.isArray(a.args) ? a.args : String(a.args ?? a.command ?? "").split(/\s+/);
        return JSON.stringify(list.filter((x) => x !== "kubectl")) === JSON.stringify(args);
      } catch {
        return false;
      }
    });
    if (!tc) continue;
    const result = t.slice(i + 1).find((x) => x.role === "tool" && x.tool_call_id === tc.id);
    const next = t.slice(i + 1).find((x) => x.role === "assistant");
    const nextCalls = (next?.tool_calls || []).map((c) => `${c.function.name} ${short(c.function.arguments, 300)}`);
    return { said: short(m.content), result: short(result?.content, 500), nextSaid: short(next?.content), nextCalls };
  }
  return null;
}

const lines = [];
const out = (s) => lines.push(s);
out(`# Actions the guardrails stopped\n\nSource: \`${file}\`. Generated by scripts/04-transcripts.mjs.\n`);

for (const r of rows) {
  const blocked = r.audit.filter((e) => ["refused", "approval-required"].includes(e.decision));
  const would = r.audit.filter((e) => e.wouldGate);
  if (!blocked.length && !would.length) continue;
  out(`## ${r.key}\n`);
  out(`Alert: ${r.alert}\n`);
  for (const e of blocked) {
    const c = contextFor(r, e.args);
    out(`- **${e.decision} (${e.guard})** at ${Math.round(e.at / 1000)}s: \`kubectl ${e.args.join(" ")}\``);
    if (c?.said) out(`  - agent, before: "${c.said}"`);
    if (c?.result) out(`  - harness replied: "${c.result}"`);
    if (c?.nextSaid) out(`  - agent, after: "${c.nextSaid}"`);
    if (c?.nextCalls?.length) out(`  - next calls: ${c.nextCalls.map((x) => `\`${x}\``).join("; ")}`);
  }
  for (const e of would) {
    out(`- **unguarded, ran; the gate would have said ${e.wouldGate.guard}**: \`kubectl ${e.args.join(" ")}\` (exit ${e.code}) - ${e.wouldGate.reason}`);
  }
  out(`- outcome: fixed=${r.fixedFinal}, escalated=${r.escalations.length > 0}, harm=${r.harm.length ? r.harm.join("; ") : "none"}`);
  out(`- final report: "${short(r.finalText, 600)}"\n`);
}
console.log(lines.join("\n"));
